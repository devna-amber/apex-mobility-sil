#!/usr/bin/env python3
"""
plant-models/thermal-twin/thermal_predictor.py
Predictive Battery Thermal Digital Twin using a 1st-Order RC Thermal Model.
"""

import sys
import numpy as np


def predict_future_temp(
    current_temp_c: float,
    ambient_temp_c: float,
    load_current_a: float,
    horizon_sec: int = 60,
) -> float:
    """Forecast battery core temperature 60 seconds into the future."""
    internal_resistance_ohm = 0.015  # 15 milliohms pack resistance
    thermal_capacitance = 1200.0     # J/K (how much heat the pack absorbs)
    cooling_conductance = 18.0       # W/K (how fast the cooling fan removes heat)

    temp = current_temp_c
    dt = 1.0  # 1-second simulation steps

    for _ in range(horizon_sec):
        # 1. Heat generated by current (P = I^2 * R)
        heat_in_watts = (load_current_a ** 2) * internal_resistance_ohm

        # 2. Heat removed by cooling system
        heat_out_watts = cooling_conductance * (temp - ambient_temp_c)

        # 3. Update temperature for the next second
        temp += ((heat_in_watts - heat_out_watts) / thermal_capacitance) * dt

    return temp


def main() -> int:
    ambient_temp = 32.0   # Warm day (32 C)
    current_temp = 44.0   # Battery is currently safe at 44 C

    print("=== APEX MOBILITY: PREDICTIVE THERMAL DIGITAL TWIN ===")
    print(f"Current Battery Temp : {current_temp:.1f} C (Safe Limit: 55.0 C)")

    # Scenario 1: Normal highway cruising (120 Amps)
    cruise_forecast = predict_future_temp(current_temp, ambient_temp, load_current_a=120.0)
    print(f"\n[Scenario 1] Normal Cruising (120A)")
    print(f" -> 60s Forecast Temp : {cruise_forecast:.2f} C [STATUS: NOMINAL]")

    # Scenario 2: Heavy uphill acceleration (320 Amps)
    sprint_forecast = predict_future_temp(current_temp, ambient_temp, load_current_a=320.0)
    print(f"\n[Scenario 2] Heavy Acceleration (320A)")
    print(f" -> 60s Forecast Temp : {sprint_forecast:.2f} C", end=" ")

    if sprint_forecast > 55.0:
        print("[ALERT: EARLY TORQUE DERATE TRIGGERED]")
        print("\n[PASS] Digital Twin predicted thermal limit breach 60s early.")
        return 0
    else:
        print("[FAIL] Digital Twin missed thermal spike.")
        return 1


if __name__ == "__main__":
    sys.exit(main())
